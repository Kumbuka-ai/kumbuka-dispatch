#!/usr/bin/env bash
# Generate the DBML view of the physical level from a database migrated with the store line.
# The view is lossy (docs/data-model/method/format.md) and is never used as evidence.
# Connection: the libpq environment. Requires pg_dump and sql2dbml (npm package @dbml/cli).
set -euo pipefail
out="${1:-docs/data-model/model/store.generated.dbml}"
tmp="$(mktemp)"
trap 'rm -f "$tmp"' EXIT
pg_dump --schema-only --no-owner --no-privileges -n dispatch \
  | sed -E 's/ON DELETE SET NULL \([a-z_]+\)/ON DELETE SET NULL/' > "$tmp"
{
  echo "// GENERATED by scripts/data-model/generate-dbml.sh from a schema dump. Do not edit."
  echo "// A view, not evidence. Known losses: timestamptz shown as timestamp; partial index predicates"
  echo "// dropped (uq_definition_version_active is one ACTIVE version per selector); row-level security,"
  echo "// policies and grants absent; ON DELETE SET NULL (column) shown without its column list."
  sql2dbml "$tmp" --postgres
} > "$out"
echo "wrote $out"
